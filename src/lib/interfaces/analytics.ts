/** Totals for the three money tables across a date range. */
export interface FinanceTotals {
	revenue: number;
	cost: number;
	expense: number;
}

/**
 * One day of a money-flow series. `day` is a 'YYYY-MM-DD' string bucketed in
 * America/Guayaquil, matching how the admin UI formats dates.
 */
export interface FinanceDailyPoint {
	day: string;
	value: number;
}

/**
 * Totals for a period and for the immediately preceding period of equal
 * length. Raw totals (not percentages) so the client computes deltas with its
 * own rounding/formatting rules.
 */
export interface PeriodComparison {
	current: FinanceTotals;
	previous: FinanceTotals;
}

/** Units sold and revenue generated by one product in completed orders. */
export interface TopProductSales {
	productId: string;
	productName: string;
	units: number;
	revenue: number;
}

/** Page views recorded for one product in the daily counter table. */
export interface TopProductViews {
	productId: string;
	productName: string;
	views: number;
}

/**
 * Surviving non-converted cart activity in a range. See
 * `getCartAbandonment` for the exact (and limited) semantics this can honestly
 * support.
 */
export interface CartAbandonment {
	items: number;
	carts: number;
	value: number;
}
