/** Totals for the three money tables across a date range. */
export interface FinanceTotals {
	revenue: number;
	cost: number;
	expense: number;
}

/**
 * One day of a money-flow series. `day` is a 'YYYY-MM-DD' string bucketed in
 * America/Guayaquil, matching how the admin UI formats dates.
 */
export interface FinanceDailyPoint {
	day: string;
	value: number;
}

/**
 * Totals for a period and for the immediately preceding period of equal
 * length. Raw totals (not percentages) so the client computes deltas with its
 * own rounding/formatting rules.
 */
export interface PeriodComparison {
	current: FinanceTotals;
	previous: FinanceTotals;
}

/** Units sold and revenue generated by one product in completed orders. */
export interface TopProductSales {
	productId: string;
	productName: string;
	units: number;
	revenue: number;
}

/** Page views recorded for one product in the daily counter table. */
export interface TopProductViews {
	productId: string;
	productName: string;
	views: number;
}

/**
 * Surviving non-converted cart activity in a range. See
 * `getCartAbandonment` for the exact (and limited) semantics this can honestly
 * support.
 */
export interface CartAbandonment {
	items: number;
	carts: number;
	value: number;
}

/** Active preset of the balance dashboard's date-range filter. */
export type FinanceRangePreset = 'month' | 'last-month' | 'last-7-days' | 'custom';

/** Ready-made hrefs for the preset filter links, computed server-side. */
export interface FinanceRangePresetHrefs {
	month: string;
	lastMonth: string;
	last7: string;
}

/** Selected dashboard range: inclusive day bounds plus preset metadata. */
export interface FinanceRange {
	/** Inclusive 'YYYY-MM-DD' first day of the range. */
	from: string;
	/** Inclusive 'YYYY-MM-DD' last day of the range. */
	to: string;
	preset: FinanceRangePreset;
	presetHrefs: FinanceRangePresetHrefs;
}

/**
 * Everything the balance dashboard renders for the selected range. All values
 * are already aggregated and zero-filled server-side; the client only formats
 * and composes them.
 */
export interface FinanceDashboard {
	range: FinanceRange;
	comparison: PeriodComparison;
	revenueSeries: FinanceDailyPoint[];
	costSeries: FinanceDailyPoint[];
	expenseSeries: FinanceDailyPoint[];
	topProductsBySales: TopProductSales[];
	/** `null` = product_view_daily unavailable (migration 0011 not applied). */
	topProductsByViews: TopProductViews[] | null;
	cartAbandonment: CartAbandonment;
}
